def load_registry():
    reg = Registry()
    for d, f in ((ACT_DIR, "ACT_POLICY_CLASS_RECORD.schema.json"), (AS_DIR, "AS_SETTINGS_IN.schema.json"),
                 (EXEC_DIR, "checkpoint-record-entries.schema.json"), (RS_DIR, "RS_RECORD.schema.json")):
        reg.load(os.path.join(d, f))
    return reg


def kind_coverage(reg):
    """Every EXEC CE body has an RS kind that references it; EXEC's output kinds are RS kinds."""
    rs = reg.by_id[RS_ID]
    exec_schema = json.load(open(os.path.join(EXEC_DIR, "checkpoint-record-entries.schema.json"), encoding="utf-8"))
    branches = exec_schema["$defs"]["recorderOutput"]["oneOf"]
    exec_kinds = {b["properties"]["kind"]["const"]: b["properties"]["body"]["$ref"].split("/")[-1] for b in branches}
    rs_kinds = set(rs["$defs"]["entry"]["properties"]["kind"]["enum"])
    rows, problems = [], []
    for kind, body in exec_kinds.items():
        if kind not in rs_kinds:
            problems.append(f"{kind}: no RS entry kind")
            continue
        rs_def = rs["$defs"].get(body)
        refs = json.dumps(rs_def or {})
        if kind == "evidence_limit":
            ok = True                       # CE-19 is a constrained instance of RS's own evidence-limit body
            how = "RS evidenceLimit (EXEC recordWriteFailed is a constrained instance)"
        else:
            ok = rs_def is not None and exec_schema["$id"] + "#/$defs/" + body in refs
            how = "$ref EXEC #/$defs/" + body if ok else "NOT referenced"
        rows.append((kind, body, how))
        if not ok:
            problems.append(f"{kind}: RS body does not reference EXEC's {body}")
    return rows, problems


def convert(scratch, reg=None, quiet=False):
    reg = reg or load_registry()
    outputs = json.load(open(os.path.join(EXEC_DIR, "checkpoint-record-entries.example.valid.json"), encoding="utf-8"))
    out = os.path.join(scratch, "exec-to-rs.run-12a.jsonl")
    if os.path.exists(out):
        os.remove(out)
    w = Writer(out, reg, {"role": "App writer", "identity": "app-writer:local"}, {"surface": "App"}, RUN_ID)
    refused = []
    w.append("run_opened", RUN_OPENED, "rec:app:run-12a:0000")
    for i, o in enumerate(outputs, start=1):
        try:
            w.append(o["kind"], o["body"], f"rec:app:run-12a:e{i:02d}", extra={"observedAt": o["observedAt"]})
        except NonConformant as exc:
            refused.append(str(exc))
    log = Reader(reg).read_log(out)
    converted = [e for e in log["entries"] if e["recordId"] != "rec:app:run-12a:0000"]
    valid = [e for e in converted if not validate(e, {"$ref": RS_ID + "#/$defs/entry"}, reg)]
    if not quiet:
        for e in converted:
            print(f"  {e['recordId']:24} {e['kind']:20} seq {e['seq']:2} observedAt {e.get('observedAt')}")
    return {"outputs": len(outputs), "converted": len(converted), "valid": len(valid), "refused": refused,
            "limits": log["limits"], "nonconformant": log["nonconformant"],
            "kinds": sorted({e["kind"] for e in converted}), "path": out}


