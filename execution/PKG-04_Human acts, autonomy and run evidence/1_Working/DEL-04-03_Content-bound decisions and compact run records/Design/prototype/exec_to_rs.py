def convert_more(scratch, reg):
    """CH-20, CH-31 (i), CH-31 (ii), CH-10 and the samples, each run into its own RS log."""
    sys.path.insert(0, os.path.join(EXEC_DIR, "prototype"))
    import run_all as ex                                        # noqa: E402  (DEL-02-03 prototype)
    exec_schema = json.load(open(os.path.join(EXEC_DIR, "checkpoint-record-entries.schema.json"), encoding="utf-8"))
    runs = [(name, fn().outputs) for name, fn in (("CH-20", ex.ch20), ("CH-31-i", ex.ch31_i),
                                                    ("CH-31-ii", ex.ch31_ii), ("CH-10", ex.ch10))]
    runs.append(("decision-package", ex.decision_package_outputs()))
    runs.append(("samples", [{"kind": k, "observedAt": t, "body": b} for k, t, b in SAMPLES]))
    total = valid = 0
    kinds, problems = set(), []
    for name, outputs in runs:
        out = os.path.join(scratch, f"exec-to-rs.{name}.jsonl")
        if os.path.exists(out):
            os.remove(out)
        w = Writer(out, reg, {"role": "App writer", "identity": "app-writer:local"}, {"surface": "App"}, "run:" + name)
        for i, o in enumerate(outputs, start=1):
            total += 1
            exec_errs = ex.validate(o, exec_schema)
            if exec_errs:
                problems.append(f"{name} #{i} not a valid EXEC recorder output: {exec_errs[:1]}")
            try:
                w.append(o["kind"], o["body"], f"rec:app:{name}:e{i:02d}", extra={"observedAt": o["observedAt"]})
            except NonConformant as exc:
                problems.append(str(exc))
            # CC-R CI-3: this file-discovery fixture observes no writer. The RS
            # recorder records the limit separately; EXEC's CE bodies stay CE bodies.
            if o["kind"] == "act_request" and o["body"].get("form") == "decision package file" and "identity" not in o["body"]["requester"]:
                total += 1
                w.append("evidence_limit", {"label": "requester identity not established",
                         "subjectRef": f"rec:app:{name}:e{i:02d}",
                         "detail": "package file observed; writer of the identified bytes not observed"},
                         f"rec:app:{name}:e{i:02d}:requester-limit")
        log = Reader(reg).read_log(out)
        good = [e for e in log["entries"] if not validate(e, {"$ref": RS_ID + "#/$defs/entry"}, reg)]
        valid += len(good)
        kinds |= {e["kind"] for e in log["entries"]}
        print(f"  {name:9} {len(outputs):2} outputs -> {len(good):2} valid RS entries")
    return total, valid, kinds, problems


def main():
    scratch = sys.argv[1] if len(sys.argv) > 1 else tempfile.mkdtemp(prefix="exec-to-rs-")
    os.makedirs(scratch, exist_ok=True)
    reg = load_registry()
    rows, problems = kind_coverage(reg)
    print("EXEC CE bodies -> RS entry kinds (R14-1):")
    for kind, body, how in rows:
        print(f"  {body:22} -> {kind:22} {how}")
    print(f"kinds without an RS kind or reference: {problems or 'none'}")
    print("\nEXEC's valid example converted into RS entries:")
    r = convert(scratch, reg)
    ok = (not problems and not r["refused"] and r["converted"] == r["outputs"] == r["valid"]
          and not r["limits"] and not r["nonconformant"])
    print(f"\n{r['valid']} of {r['outputs']} recorder outputs written and valid as RS entries; refused {len(r['refused'])}; "
          f"reader limits {r['limits'] or 'none'}; kinds {r['kinds']}")
    print("\nEXEC's other CH scripts and one sample of each remaining CE kind:")
    total, valid, kinds, more = convert_more(scratch, reg)
    all_kinds = {k for k, _, _ in rows}
    missing = sorted(all_kinds - kinds - set(r["kinds"]))
    print(f"{valid} of {total} written and valid; problems {more or 'none'}; CE-referencing kinds never written: {missing or 'none'}")
    ok = ok and not more and valid == total and not missing
    print("RESULT:", "every entry valid, none without a kind" if ok else "FAILED")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
