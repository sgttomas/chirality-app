"""Convert EXEC's valid recorder outputs into RS entries and validate each one (R14-1).

Prototype only (R12-3); Python 3 standard library; not product code.

  python3 exec_to_rs.py [scratch-dir]

RS format 0.1 is the only record container (R14-1). DEL-02-03's recorder
emits {kind, observedAt, body}, where kind is an RS entry kind and body is a
CE body of EXEC's `checkpoint-record-entries.schema.json`. This script:

1. checks that every CE body EXEC defines has an RS entry kind whose body
   `$ref`s it by its schema identity (none without a kind), and that EXEC's
   recorder-output kinds and RS's kinds agree;
2. writes an RS `run_opened` for the fixture run (the App writer's entry,
   RS §14.1), then appends each recorder output of EXEC's committed valid
   example through the RS prototype writer (W-1 validates every entry against
   `RS_RECORD.schema.json` and refuses a nonconformant one);
3. reads the log back (R-1…R-8) and reports n of n entries valid;
4. does the same for every recorder output of EXEC's other CH scripts
   (CH-20, CH-31 (i), CH-31 (ii), CH-10, regenerated by EXEC's `run_all.py`)
   and for one sample body of each CE kind those scripts do not emit, so that
   every RS kind that references an EXEC body is written at least once.

Exit status 0 only when every entry is valid and every kind resolves.
"""

