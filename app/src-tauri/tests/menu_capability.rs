//! Locked Tauri ACL resolution and actual mock-runtime IPC admission. No native
//! window/menu UI, App state, keychain, supplier or signing is exercised.
use serde_json::{json, Value};
use std::{
    collections::{BTreeMap, BTreeSet},
    path::Path,
};
use tauri_utils::{
    acl::{capability::Capability, manifest::Manifest, resolved::Resolved},
    platform::Target,
};
const CAP: &str = include_str!("../capabilities/default.json");
const EXPECTED: [&str; 8] = [
    "core:path:default",
    "core:event:default",
    "core:window:default",
    "core:webview:default",
    "core:app:default",
    "core:image:default",
    "core:resources:default",
    "core:tray:default",
];
fn manifests() -> BTreeMap<String, Manifest> {
    // Generated by the actual locked tauri-build dependency, never a hand-copied
    // fixture manifest. Missing generated data fails this integration test.
    serde_json::from_str(include_str!("../gen/schemas/acl-manifests.json")).unwrap()
}
fn generated_resolution() -> Resolved {
    let capabilities: BTreeMap<String, Capability> =
        serde_json::from_str(include_str!("../gen/schemas/capabilities.json")).unwrap();
    assert_eq!(capabilities.keys().collect::<Vec<_>>(), vec!["default"]);
    Resolved::resolve(&manifests(), capabilities, Target::MacOS).unwrap()
}
fn resolve(value: Value) -> Resolved {
    let cap: Capability = serde_json::from_value(value).unwrap();
    Resolved::resolve(
        &manifests(),
        BTreeMap::from([(cap.identifier.clone(), cap)]),
        Target::MacOS,
    )
    .unwrap()
}
#[test]
fn locked_expansion_removes_only_menu_and_no_other_capability_regrants_it() {
    let lock: toml::Value = toml::from_str(include_str!("../Cargo.lock")).unwrap();
    let tauri = lock["package"]
        .as_array()
        .unwrap()
        .iter()
        .find(|p| p["name"].as_str() == Some("tauri"))
        .unwrap();
    assert_eq!(
        tauri["version"].as_str(),
        Some("2.11.1"),
        "inspect expansion on supplier advance"
    );
    let value: Value = serde_json::from_str(CAP).unwrap();
    assert_eq!(value["permissions"], json!(EXPECTED));
    assert_eq!(value["identifier"], "default");
    assert_eq!(value["windows"], json!(["main"]));
    assert!(value.get("remote").is_none());
    assert!(value.get("webviews").is_none());
    let directory = Path::new(env!("CARGO_MANIFEST_DIR")).join("capabilities");
    let files = std::fs::read_dir(directory)
        .unwrap()
        .map(|p| p.unwrap().file_name().to_string_lossy().into_owned())
        .collect::<Vec<_>>();
    assert_eq!(
        files,
        vec!["default.json"],
        "inspect new capabilities for additive regrants"
    );
    let manifest: Value =
        serde_json::from_str(include_str!("../gen/schemas/acl-manifests.json")).unwrap();
    let expanded = manifest["core"]["default_permission"]["permissions"]
        .as_array()
        .unwrap();
    let non_menu = expanded
        .iter()
        .filter(|v| **v != json!("core:menu:default"))
        .cloned()
        .collect::<Vec<_>>();
    assert_eq!(non_menu, json!(EXPECTED).as_array().unwrap().clone());
    assert_eq!(expanded.len(), 9);
    let generated: Value =
        serde_json::from_str(include_str!("../gen/schemas/capabilities.json")).unwrap();
    let mut expected_generated = value.clone();
    expected_generated
        .as_object_mut()
        .unwrap()
        .remove("$schema");
    expected_generated["local"] = json!(true);
    assert_eq!(
        generated,
        json!({"default":expected_generated}),
        "actual compiled capabilities must match the approved file with no inline/config regrant"
    );
    let narrowed = generated_resolution();
    let mut old = value;
    old["permissions"] = json!(["core:default"]);
    let old = resolve(old);
    let before = old
        .allowed_commands
        .keys()
        .cloned()
        .collect::<BTreeSet<_>>();
    let after = narrowed
        .allowed_commands
        .keys()
        .cloned()
        .collect::<BTreeSet<_>>();
    assert!(after.is_subset(&before));
    let removed = before.difference(&after).collect::<Vec<_>>();
    assert_eq!(removed.len(), 22);
    assert!(removed.iter().all(|name| name.starts_with("plugin:menu|")));
    for name in before
        .iter()
        .filter(|name| !name.starts_with("plugin:menu|"))
    {
        assert!(after.contains(name), "lost non-menu permission {name}");
    }
    assert_eq!(narrowed.has_app_acl, old.has_app_acl);
    let schema: Value =
        serde_json::from_str(include_str!("../gen/schemas/desktop-schema.json")).unwrap();
    jsonschema::validator_for(&schema)
        .unwrap()
        .validate(&serde_json::from_str::<Value>(CAP).unwrap())
        .unwrap();
}
#[tauri::command]
fn app_command_probe() -> &'static str {
    "existing App command path"
}
fn app() -> tauri::App<tauri::test::MockRuntime> {
    let mut context = tauri::test::mock_context(tauri::test::noop_assets());
    *context.runtime_authority_mut() =
        tauri::runtime_authority!(manifests(), generated_resolution());
    tauri::test::mock_builder()
        .invoke_handler(tauri::generate_handler![app_command_probe])
        .build(context)
        .unwrap()
}
fn ipc(
    window: &tauri::WebviewWindow<tauri::test::MockRuntime>,
    command: &str,
    body: Value,
) -> Result<tauri::ipc::InvokeResponseBody, Value> {
    tauri::test::get_ipc_response(
        window,
        tauri::webview::InvokeRequest {
            cmd: command.into(),
            callback: tauri::ipc::CallbackFn(0),
            error: tauri::ipc::CallbackFn(1),
            url: if cfg!(windows) {
                "http://tauri.localhost"
            } else {
                "tauri://localhost"
            }
            .parse()
            .unwrap(),
            body: tauri::ipc::InvokeBody::Json(body),
            headers: Default::default(),
            invoke_key: tauri::test::INVOKE_KEY.into(),
        },
    )
}
#[test]
fn every_menu_ipc_is_rejected_before_handler_including_forged_host_item() {
    let app = app();
    let main = tauri::WebviewWindowBuilder::new(&app, "main", tauri::WebviewUrl::default())
        .build()
        .unwrap();
    let mut prior: Value = serde_json::from_str(CAP).unwrap();
    prior["permissions"] = json!(["core:default"]);
    let menu = resolve(prior)
        .allowed_commands
        .keys()
        .filter(|name| name.starts_with("plugin:menu|"))
        .cloned()
        .collect::<Vec<_>>();
    assert_eq!(menu.len(), 22);
    for command in menu {
        let error=ipc(&main,&command,json!({"kind":"MenuItem","options":{"id":"chirality-prepare-capture-sealing","text":"misleading label","enabled":true},"rid":1})).err().expect("menu IPC must be denied");
        let message = error.to_string();
        assert!(
            message.contains("not allowed") || message.contains("not permitted"),
            "{command}: {message}"
        );
        assert!(
            !message.contains("invalid args"),
            "rejection must occur before handler parsing"
        );
    }
}
#[test]
fn waiting_event_subscription_and_app_command_paths_still_work() {
    let app = app();
    let main = tauri::WebviewWindowBuilder::new(&app, "main", tauri::WebviewUrl::default())
        .build()
        .unwrap();
    assert_eq!(
        ipc(&main, "app_command_probe", json!({}))
            .unwrap()
            .deserialize::<String>()
            .unwrap(),
        "existing App command path"
    );
    let event_id = ipc(
        &main,
        "plugin:event|listen",
        json!({"event":"chirality-native-waiting","target":{"kind":"Any"},"handler":42}),
    )
    .unwrap()
    .deserialize::<u32>()
    .unwrap();
    ipc(
        &main,
        "plugin:event|unlisten",
        json!({"event":"chirality-native-waiting","eventId":event_id}),
    )
    .unwrap();
    let other = tauri::WebviewWindowBuilder::new(&app, "other", tauri::WebviewUrl::default())
        .build()
        .unwrap();
    assert!(
        ipc(
            &other,
            "plugin:event|listen",
            json!({"event":"chirality-native-waiting","target":{"kind":"Any"},"handler":42})
        )
        .is_err(),
        "do not broaden main-window scope"
    );
}
