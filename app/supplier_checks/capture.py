#!/usr/bin/env python3
"""Record exchanges from the stock Codex App Server at one pin (DEL-01-01 OUT-004).

This stands in for the App side of the standard-input/output boundary and records
every frame at the pipe. It is not an App candidate and qualifies nothing: a
recording is an input to the version-advance comparison and to replay tests.

Before the supplier is executed, the complete vendor tree is compared with the
committed expected inventory of the pin
(`src-tauri/resources/supplier/<pin>/CANONICAL_DISTRIBUTION.json`): every member's
type, mode, size and content digest, with nothing missing or extra. A difference
refuses. The version label must then equal the pin.

Isolation. The supplier runs with an environment of five variables only (HOME,
CODEX_HOME, TMPDIR, PATH, LANG), all under a fresh private scratch directory, so
it reads no person's Codex home or settings. No sign-in, credential or model is
used: the model provider is `stub_provider.py` on 127.0.0.1 with scripted invented
output, and plugins and analytics are off in the scratch `config.toml`. A 0.25 s
sample of the supplier process group's sockets stops the run at the first
non-loopback peer and is reported in the recording; it is a sample, not network
isolation.

Scenarios
  st5       generation 1: initialize, thread/start, turn/start; the stub asks for one
            shell command; Codex raises item/commandExecution/requestApproval; the
            process group is frozen (SIGSTOP), the answer and one client request are
            written, and the group is ended (SIGKILL) while frozen, so no
            acknowledgment can have been sent. Generation 2, same home: initialize,
            thread/read with turns, thread/turns/list, thread/loaded/list,
            thread/resume, a short wait for a re-raised request, graceful stop.
  st5-race  as st5 without the freeze: the answer is written and the group killed at
            once; whether serverRequest/resolved precedes the kill is the observation.
  nv04      a parent turn whose model output spawns one sub-agent through Codex's own
            collaboration tool; the stub holds the child's response open so the
            parent's turn ends first. After the child ends: thread/loaded/list, then
            history reads of the parent (thread/read with turns, thread/turns/list,
            thread/items/list for the turn) and thread/read of the child. Generation
            2, same home, repeats those four reads after a restart.

Usage, from `app/`:
  python3 supplier_checks/capture.py --vendor /absolute/vendor --pin 0.167.0 \
      --out /absolute/new-scratch SCENARIO

`--out` receives the raw local frames and the redacted `<scenario>.recording.json`.
Only the redacted recording is committed, under `supplier_checks/recordings/<pin>/`.
Thread identifiers and times differ on every run; a recording is made once per pin
and is not regenerated by a test.
"""
