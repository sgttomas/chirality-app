class Refused(Exception):
    pass


def sha256_file(path):
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def expected_distribution(pin, resources=None):
    path = Path(resources or HERE.parent / "src-tauri/resources/supplier") / pin / "CANONICAL_DISTRIBUTION.json"
    try:
        record = json.loads(path.read_bytes())
    except (OSError, ValueError):
        raise Refused("no expected distribution is committed for pin %s" % pin) from None
    if record.get("pin") != pin or record.get("package_metadata", {}).get("version") != pin:
        raise Refused("the expected distribution record does not name pin %s" % pin)
    return record


def vendor_differences(vendor, inventory):
    """Every difference between the tree at `vendor` and the expected member inventory."""
    expected = {entry["path"]: entry for entry in inventory["entries"]}
    differences, seen = [], set()
    for folder, directories, files in os.walk(vendor, followlinks=False):
        for name in directories + files:
            path = os.path.join(folder, name)
            relative = os.path.relpath(path, vendor)
            seen.add(relative)
            entry, status = expected.get(relative), os.lstat(path)
            if entry is None:
                differences.append("extra: " + relative)
            elif stat.S_ISLNK(status.st_mode) or not (
                    stat.S_ISDIR(status.st_mode) if entry["kind"] == "dir" else stat.S_ISREG(status.st_mode)):
                differences.append("type: " + relative)
            elif stat.S_IMODE(status.st_mode) != entry["mode"]:
                differences.append("mode: " + relative)
            elif entry["kind"] == "file" and (status.st_size != entry["size"]
                                              or sha256_file(path) != entry["sha256"]):
                differences.append("content: " + relative)
    differences += ["missing: " + path for path in expected if path not in seen]
    return sorted(differences)


def verified_vendor(vendor, pin, resources=None):
    """Return (record, entrypoint, path directory) or refuse; nothing is executed here."""
    record = expected_distribution(pin, resources)
    vendor = os.path.realpath(vendor)
    if not os.path.isdir(vendor):
        raise Refused("the vendor tree is not a directory")
    differences = vendor_differences(vendor, record["inventory"])
    if differences:
        raise Refused("the vendor tree differs from the expected %s inventory: %s%s" % (
            pin, "; ".join(differences[:6]), "; %d more" % (len(differences) - 6) if len(differences) > 6 else ""))
    metadata = record["package_metadata"]
    return record, os.path.join(vendor, metadata["entrypoint"]), os.path.join(vendor, metadata["pathDir"])


class Generation:
    """One Codex App Server process and its standard-input/output tap."""

    def __init__(self, harness, number):
        self.h, self.number = harness, number
        self.send_position = self.receive_position = self.next_id = 0
        self.results, self.server_requests, self.notes = {}, [], []
        self.cv, self.lock, self.eof = threading.Condition(), threading.Lock(), threading.Event()

    def frame(self, direction, raw):
        with self.lock:
            if direction == "app->codex":
                self.send_position += 1
                position = self.send_position
            else:
                self.receive_position += 1
                position = self.receive_position
            self.h.frames.append({"generation": self.number, "direction": direction, "position": position,
                                  "t_ms": self.h.elapsed(), "raw": raw})

    def start(self):
        self.proc = subprocess.Popen([self.h.binary, "app-server"], cwd=self.h.work, env=self.h.environment(),
                                     stdin=subprocess.PIPE, stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                                     start_new_session=True)
        self.pgid = os.getpgid(self.proc.pid)
        self.h.event("spawn", generation=self.number)
        threading.Thread(target=self._reader, daemon=True).start()
        threading.Thread(target=self._stderr, daemon=True).start()

    def _reader(self):
        for line in self.proc.stdout:
            raw = line.decode("utf-8", "replace").rstrip("\n")
            self.frame("codex->app", raw)
            try:
                message = json.loads(raw)
            except ValueError:
                continue
            with self.cv:
                if "id" in message and "method" not in message:
                    self.results[message["id"]] = message
                elif "id" in message:
                    self.server_requests.append(message)
                else:
                    self.notes.append(message)
                self.cv.notify_all()
        self.eof.set()
        with self.cv:
            self.cv.notify_all()

    def _stderr(self):
        data = self.proc.stderr.read() or b""
        self.h.stderr[self.number] = len(data)
        with open(os.path.join(self.h.out, "gen%d.stderr.local" % self.number), "wb") as handle:
            handle.write(data)

    def send(self, message):
        raw = json.dumps(message, separators=(",", ":"), ensure_ascii=False)
        self.frame("app->codex", raw)
        self.proc.stdin.write((raw + "\n").encode("utf-8"))
        self.proc.stdin.flush()

    def request(self, method, params, timeout=60):
        self.next_id += 1
        request_id = self.next_id
        self.send({"jsonrpc": "2.0", "id": request_id, "method": method, "params": params})
        return self.wait(lambda: self.results.get(request_id), timeout)

    def wait(self, predicate, timeout):
        end = time.monotonic() + timeout
        with self.cv:
            while True:
                value = predicate()
                if value or self.h.stop_reason:
                    return value
                left = end - time.monotonic()
                if left <= 0 or self.eof.is_set():
                    return predicate()
                self.cv.wait(min(left, 0.2))

    def initialize(self):
        reply = self.request("initialize", {"clientInfo": CLIENT, "capabilities": CAPABILITIES})
        if not reply or "result" not in reply:
            raise Refused("initialize failed (return code %r)" % (self.proc.poll(),))
        if os.path.realpath(reply["result"].get("codexHome") or "") != self.h.home:
            raise Refused("the supplier reports a Codex home that is not the scratch home")
        self.send({"jsonrpc": "2.0", "method": "initialized"})
        return reply["result"]


class Harness:
    def __init__(self, binary, codex_path, out, child_hold):
        self.binary, self.codex_path, self.child_hold = binary, codex_path, child_hold
        self.frames, self.events, self.provider_log, self.gens = [], [], [], []
        self.stderr, self.stop_reason, self.started = {}, None, time.monotonic()
        self.socket_samples, self.loopback_peers = 0, set()
        self.out = os.path.realpath(out)
        os.makedirs(self.out, exist_ok=True)
        self.scratch = os.path.realpath(tempfile.mkdtemp(prefix="supplier-capture-"))
        self.home, self.work, self.user_home, self.tmp = (
            os.path.join(self.scratch, name) for name in ("home", "workspace", "user-home", "tmp"))
        for folder in (self.home, self.work, self.user_home, self.tmp):
            os.makedirs(folder)
        with open(os.path.join(self.work, "README.md"), "w") as handle:
            handle.write("Invented pump-skid example workspace (ST-5 capture).\n")

    def environment(self):
        return {"HOME": self.user_home, "CODEX_HOME": self.home, "TMPDIR": self.tmp,
                "PATH": self.codex_path + os.pathsep + SYSTEM_PATH, "LANG": "en_US.UTF-8"}

    def elapsed(self):
        return round((time.monotonic() - self.started) * 1000, 1)

    def event(self, kind, **fields):
        record = {"event": kind, "t_ms": self.elapsed()}
        record.update(fields)
        self.events.append(record)
        sys.stderr.write("[%8.1f] %s %s\n" % (record["t_ms"], kind, json.dumps(fields)[:300]))

    def watch_sockets(self, done):
        while not done.is_set():
            for generation in list(self.gens):
                if generation.proc.poll() is not None:
                    continue
                listing = subprocess.run(["/usr/sbin/lsof", "-n", "-P", "-a", "-i", "-g", str(generation.pgid)],
                                         capture_output=True, text=True).stdout
                self.socket_samples += 1
                for line in listing.splitlines()[1:]:
                    peer = re.search(r"->\[?([0-9a-fA-F:.]+)\]?:\d+", line)
                    if not peer:
                        continue
                    if peer.group(1) in ("127.0.0.1", "::1"):
                        self.loopback_peers.add(peer.group(1))
                    elif not self.stop_reason:
                        self.stop_reason = "non-loopback socket: " + peer.group(1)
                        self.event("STOP", reason=self.stop_reason)
                        os.killpg(generation.pgid, signal.SIGKILL)
            done.wait(0.25)

    def write_config(self, port):
        with open(os.path.join(self.home, "config.toml"), "w") as handle:
            handle.write(CONFIG.format(model=SP.MODEL, approval=APPROVAL, sandbox=SANDBOX, port=port))

    def gen(self):
        generation = Generation(self, len(self.gens) + 1)
        self.gens.append(generation)
        generation.start()
        return generation

    def end(self, generation, how):
        if how == "stdin":
            generation.proc.stdin.close()
        else:
            os.killpg(generation.pgid, getattr(signal, how))
        try:
            code = generation.proc.wait(timeout=15)
        except subprocess.TimeoutExpired:
            os.killpg(generation.pgid, signal.SIGKILL)
            code = generation.proc.wait()
        generation.eof.wait(5)
        time.sleep(0.3)
        groups = subprocess.run(["/bin/ps", "-axo", "pgid="], capture_output=True, text=True).stdout.split()
        left = groups.count(str(generation.pgid))
        if left:
            try:
                os.killpg(generation.pgid, signal.SIGKILL)
            except ProcessLookupError:
                pass
        self.event("exit", generation=generation.number, how=how, returncode=code, group_members_left=left)


# ---------- provider plans ----------
def tool_names(body):
    names = []
    for tool in (body or {}).get("tools") or []:
        if tool.get("type") == "namespace":
            names += ["%s.%s" % (tool.get("name"), inner.get("name")) for inner in tool.get("tools") or []]
        else:
            names.append(tool.get("name") or tool.get("type"))
    return names


def has_output(body):
    return any(isinstance(item, dict) and item.get("type", "").endswith("_output")
               for item in (body or {}).get("input") or [])


def shell_call(body, call_id):
    names = tool_names(body)
    call = {"type": "function_call", "call_id": call_id, "id": "fc_" + call_id}
    if "exec_command" in names:
        return dict(call, name="exec_command", arguments=json.dumps({
            "cmd": COMMAND, "workdir": None, "sandbox_permissions": "require_escalated",
            "justification": "Create the invented marker folder."}))
    if "shell_command" in names:
        return dict(call, name="shell_command", arguments=json.dumps({"command": COMMAND}))
    return dict(call, name="shell", arguments=json.dumps({"command": ["bash", "-lc", COMMAND]}))


def st5_plan(index, body):
    if has_output(body):
        return ([SP.message("Done.", "msg_st5_done")], 0, "final message")
    return ([shell_call(body, "call_st5_1")], 0, "shell call")


def nv04_plan(harness):
    state = {"spawned": False}

    def plan(index, body):
        if CHILD_MARKER in json.dumps(body or {}) and not has_output(body) and state["spawned"]:
            return ([SP.message("Child finished counting.", "msg_child")], harness.child_hold, "child held")
        if has_output(body):
            return ([SP.message("Parent turn done; child still working.", "msg_parent_done")], 0, "parent final")
        spawn = next((name for name in tool_names(body) if name.split(".")[-1] == "spawn_agent"), None)
        if spawn is None:
            return ([SP.message("No spawn tool offered.", "msg_nospawn")], 0, "no spawn tool")
        state["spawned"] = True
        for tool in body.get("tools") or []:
            for inner in tool.get("tools") or []:
                if inner.get("name") == "spawn_agent":
                    parameters = inner.get("parameters") or {}
                    harness.event("spawn-tool-parameters", parameters=sorted(parameters.get("properties", {})),
                                  required=parameters.get("required"))
        namespace, _, name = spawn.rpartition(".")
        item = {"type": "function_call", "name": name, "call_id": "call_spawn_1", "id": "fc_spawn_1",
                "arguments": json.dumps({"message": CHILD_MARKER + ": count the invented files.",
                                         "task_name": "count_files"})}
        if namespace:
            item["namespace"] = namespace
        return ([item], 0, "spawn call")
    return plan


