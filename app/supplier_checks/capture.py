CHILD_HOLD, STEP_TIMEOUT = 8.0, 60.0


def record_scenario(vendor, record, out, scenario, child_hold=CHILD_HOLD, step_timeout=STEP_TIMEOUT):
    """Run one scenario against the tree the record describes. Returns the recording's path or refuses."""
    verified_vendor(vendor, record)
    h = Harness(vendor, record, out, child_hold, step_timeout)
    done = threading.Event()
    watcher = threading.Thread(target=h.watch_sockets, args=(done,), daemon=True)
    watcher.start()
    try:
        probe = subprocess.run([h.admitted_binary(), "--version"], capture_output=True, text=True, cwd=h.work,
                               env=h.environment(), timeout=30)
        version = probe.stdout.strip()
        if probe.returncode != 0 or version != "codex-cli " + record["pin"]:
            raise Refused("the version command exited %d with the label %r, not the pin"
                          % (probe.returncode, version))
        h.event("begin", scenario=scenario, pin=record["pin"])
        init = scenario_nv04(h) if scenario == "nv04" else scenario_st5(h, scenario == "st5")
        # Observation ends here. The watch is stopped and its sample in flight, if any, is waited
        # for, and so is every reader of the supplier's output, so nothing observes after the
        # health decision below and nothing can change what the recording says about it.
        done.set()
        watcher.join()
        h.settle()
        if h.stop_reason or h.failed_samples or not h.socket_samples or h.unsampled_generations():
            raise Refused("stopped: " + (h.stop_reason or "the socket watch took no sample of generation %s"
                                         % (h.unsampled_generations() or "any")))
        return write_recording(h, scenario, record, init, version)
    except subprocess.TimeoutExpired:
        raise Refused("the version command did not answer in time") from None
    finally:
        done.set()
        for generation in h.gens:
            if generation.proc.poll() is None:
                kill_group(generation.pgid)
        shutil.rmtree(h.scratch, ignore_errors=True)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--vendor", required=True, help="root of the complete stock vendor tree")
    parser.add_argument("--pin", required=True, choices=sorted(PINS))
    parser.add_argument("--out", required=True, help="directory that receives <scenario>.recording.json")
    parser.add_argument("scenario", choices=SCENARIOS)
    args = parser.parse_args(argv)
    try:
        print(record_scenario(args.vendor, expected_distribution(args.pin), args.out, args.scenario))
        return 0
    except Refused as refusal:
        sys.stderr.write("refused: %s\n" % refusal)
        return 2


