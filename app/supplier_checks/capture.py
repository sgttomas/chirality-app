#!/usr/bin/env python3
"""Record exchanges from the stock Codex App Server at one pin (DEL-01-01 OUT-004).

This stands in for the App side of the standard-input/output boundary and records
every frame at the pipe. It is not an App candidate and qualifies nothing: a
recording is an input to the version-advance comparison and to replay tests.

A pin is one of the table `PINS` below and nothing else: the pins that have a
consumer today, each with its release archive's size and digest. Before the
supplier is executed, the pin's committed distribution record
(`src-tauri/resources/supplier/<pin>/CANONICAL_DISTRIBUTION.json`) must name that
archive, and the complete vendor tree is compared with the record's inventory:
every member's type, mode, size and content digest, with nothing missing or
extra. A difference refuses. The version command must then exit 0 with the pin's
label.

Isolation. The supplier runs with an environment of six variables only (HOME,
CODEX_HOME, TMPDIR, PATH, LANG, TZ), the first three under a fresh private scratch
directory. TZ is UTC so that a recording does not depend on the host's clock
setting; that is a capture control, and the App starts Codex with the person's
own environment. Before any execution the run refuses when configuration from
outside the fresh homes could reach the supplier: a `.git` or `.codex` entry in
any ancestor of the scratch workspace, the system folder `/etc/codex`, or a
managed preference the supplier reads. These are controls on what the supplier
is given, not a sandbox: they do not stop supplier code opening a file by its
absolute path. No sign-in, credential or model is used: the model provider is
`stub_provider.py` on 127.0.0.1 with scripted invented output, and plugins and analytics are off in the scratch `config.toml`. A 0.25 s
sample of the supplier process group's sockets stops the run at the first
non-loopback peer and is reported in the recording; it is a sample, not network
isolation.

Scenarios
  st5       generation 1: initialize, thread/start, turn/start; the stub asks for one
            shell command; Codex raises item/commandExecution/requestApproval; the
            process group is frozen (SIGSTOP), the answer and one client request are
            written, and the group is ended (SIGKILL) while frozen, so no
            acknowledgment can have been sent. Generation 2, same home: initialize,
            thread/read with turns, thread/turns/list, thread/loaded/list,
            thread/resume, a short wait for a re-raised request, graceful stop.
  st5-race  as st5 without the freeze: the answer is written and the group killed at
            once; whether serverRequest/resolved precedes the kill is the observation.
  nv04      a parent turn whose model output spawns one sub-agent through Codex's own
            collaboration tool; the stub holds the child's response open so the
            parent's turn ends first. After the child ends: thread/loaded/list, then
            history reads of the parent (thread/read with turns, thread/turns/list,
            thread/items/list for the turn) and thread/read of the child. Generation
            2, same home, repeats those four reads after a restart.

Usage, from `app/`:
  python3 supplier_checks/capture.py --vendor /absolute/vendor --pin 0.167.0 \
      --out /absolute/new-scratch SCENARIO

`--out` receives the redacted `<scenario>.recording.json` and nothing else; it is
committed under `supplier_checks/recordings/<pin>/`. This tool writes no
unredacted frame to disk. Observation ends before the recording is decided: the socket
watch, the readers of the supplier's output and the stub provider are all stopped
and waited for first, and a failed sample, an unsampled generation, a reply that
never came or a reader that did not stop means no recording. Thread identifiers
and times differ on every run; a recording is made once per pin
and is not regenerated by a test.
"""
