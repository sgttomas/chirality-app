def tool_names(body):
    names = []
    for tool in (body or {}).get("tools") or []:
        if tool.get("type") == "namespace":
            names += ["%s.%s" % (tool.get("name"), inner.get("name")) for inner in tool.get("tools") or []]
        else:
            names.append(tool.get("name") or tool.get("type"))
    return names


def has_output(body):
    return any(isinstance(item, dict) and item.get("type", "").endswith("_output")
               for item in (body or {}).get("input") or [])


def shell_call(body, call_id):
    names = tool_names(body)
    call = {"type": "function_call", "call_id": call_id, "id": "fc_" + call_id}
    if "exec_command" in names:
        return dict(call, name="exec_command", arguments=json.dumps({
            "cmd": COMMAND, "workdir": None, "sandbox_permissions": "require_escalated",
            "justification": "Create the invented marker folder."}))
    if "shell_command" in names:
        return dict(call, name="shell_command", arguments=json.dumps({"command": COMMAND}))
    return dict(call, name="shell", arguments=json.dumps({"command": ["bash", "-lc", COMMAND]}))


def st5_plan(index, body):
    if has_output(body):
        return ([SP.message("Done.", "msg_st5_done")], 0, "final message")
    return ([shell_call(body, "call_st5_1")], 0, "shell call")


def nv04_plan(harness):
    state = {"spawned": False}

    def plan(index, body):
        if CHILD_MARKER in json.dumps(body or {}) and not has_output(body) and state["spawned"]:
            return ([SP.message("Child finished counting.", "msg_child")], harness.child_hold, "child held")
        if has_output(body):
            return ([SP.message("Parent turn done; child still working.", "msg_parent_done")], 0, "parent final")
        spawn = next((name for name in tool_names(body) if name.split(".")[-1] == "spawn_agent"), None)
        if spawn is None:
            return ([SP.message("No spawn tool offered.", "msg_nospawn")], 0, "no spawn tool")
        state["spawned"] = True
        for tool in body.get("tools") or []:
            for inner in tool.get("tools") or []:
                if inner.get("name") == "spawn_agent":
                    parameters = inner.get("parameters") or {}
                    harness.event("spawn-tool-parameters", parameters=sorted(parameters.get("properties", {})),
                                  required=parameters.get("required"))
        namespace, _, name = spawn.rpartition(".")
        item = {"type": "function_call", "name": name, "call_id": "call_spawn_1", "id": "fc_spawn_1",
                "arguments": json.dumps({"message": CHILD_MARKER + ": count the invented files.",
                                         "task_name": "count_files"})}
        if namespace:
            item["namespace"] = namespace
        return ([item], 0, "spawn call")
    return plan


